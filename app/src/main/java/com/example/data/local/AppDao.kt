package com.example.data.local

import androidx.room.Dao
import androidx.room.Insert
import androidx.room.OnConflictStrategy
import androidx.room.Query
import androidx.room.Update
import kotlinx.coroutines.flow.Flow

@Dao
interface AppDao {
    // Profile
    @Query("SELECT * FROM student_profile WHERE id = 'main' LIMIT 1")
    fun observeProfile(): Flow<StudentProfileEntity?>

    @Query("SELECT * FROM student_profile WHERE id = 'main' LIMIT 1")
    suspend fun getProfileOnce(): StudentProfileEntity?

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun upsertProfile(profile: StudentProfileEntity)

    // Subjects
    @Query("SELECT * FROM subjects ORDER BY priority DESC, createdAtEpochMs ASC")
    fun observeSubjects(): Flow<List<SubjectEntity>>

    @Query("SELECT * FROM subjects")
    suspend fun getSubjectsOnce(): List<SubjectEntity>

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun upsertSubject(subject: SubjectEntity)

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun upsertSubjects(subjects: List<SubjectEntity>)

    @Query("DELETE FROM subjects WHERE id = :subjectId")
    suspend fun deleteSubject(subjectId: String)

    // Lessons
    @Query("SELECT * FROM lessons ORDER BY dueDateEpochDay ASC, difficultyOrImportance DESC")
    fun observeLessons(): Flow<List<LessonEntity>>

    @Query("SELECT * FROM lessons")
    suspend fun getLessonsOnce(): List<LessonEntity>

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun upsertLesson(lesson: LessonEntity)

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun upsertLessons(lessons: List<LessonEntity>)

    @Query("DELETE FROM lessons WHERE id = :lessonId")
    suspend fun deleteLesson(lessonId: String)

    @Query("DELETE FROM lessons WHERE subjectId = :subjectId")
    suspend fun deleteLessonsBySubject(subjectId: String)

    // Schedule Blocks
    @Query("SELECT * FROM schedule_blocks ORDER BY dayOfWeek ASC, startMinutes ASC, orderIndex ASC")
    fun observeScheduleBlocks(): Flow<List<ScheduleBlockEntity>>

    @Query("SELECT * FROM schedule_blocks")
    suspend fun getScheduleBlocksOnce(): List<ScheduleBlockEntity>

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun upsertScheduleBlock(block: ScheduleBlockEntity)

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun upsertScheduleBlocks(blocks: List<ScheduleBlockEntity>)

    @Query("DELETE FROM schedule_blocks WHERE id = :blockId")
    suspend fun deleteScheduleBlock(blockId: String)

    @Query("DELETE FROM schedule_blocks WHERE fixed = 0 AND category = 'STUDY'")
    suspend fun deleteNonFixedStudyBlocks()

    @Query("DELETE FROM schedule_blocks WHERE fixed = 0 AND (category = 'STUDY' OR category = 'BREAK')")
    suspend fun deleteAutoGeneratedBlocks()

    // Exams
    @Query("SELECT * FROM exams ORDER BY examDateEpochDay ASC, timeMinutes ASC")
    fun observeExams(): Flow<List<ExamEntity>>

    @Query("SELECT * FROM exams")
    suspend fun getExamsOnce(): List<ExamEntity>

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun upsertExam(exam: ExamEntity)

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun upsertExams(exams: List<ExamEntity>)

    @Query("DELETE FROM exams WHERE id = :examId")
    suspend fun deleteExam(examId: String)

    // Focus Sessions
    @Query("SELECT * FROM focus_sessions ORDER BY completedAtEpochMs DESC")
    fun observeFocusSessions(): Flow<List<FocusSessionEntity>>

    @Query("SELECT * FROM focus_sessions")
    suspend fun getFocusSessionsOnce(): List<FocusSessionEntity>

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertFocusSession(session: FocusSessionEntity)

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertFocusSessions(sessions: List<FocusSessionEntity>)

    // Notes
    @Query("SELECT * FROM study_notes ORDER BY important DESC, updatedAtEpochMs DESC")
    fun observeNotes(): Flow<List<StudyNoteEntity>>

    @Query("SELECT * FROM study_notes")
    suspend fun getNotesOnce(): List<StudyNoteEntity>

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun upsertNote(note: StudyNoteEntity)

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun upsertNotes(notes: List<StudyNoteEntity>)

    @Query("DELETE FROM study_notes WHERE id = :noteId")
    suspend fun deleteNote(noteId: String)

    // Holidays
    @Query("SELECT * FROM holidays ORDER BY dateEpochDay ASC")
    fun observeHolidays(): Flow<List<HolidayOrBreakEntity>>

    @Query("SELECT * FROM holidays")
    suspend fun getHolidaysOnce(): List<HolidayOrBreakEntity>

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun upsertHoliday(holiday: HolidayOrBreakEntity)

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun upsertHolidays(holidays: List<HolidayOrBreakEntity>)

    @Query("DELETE FROM holidays WHERE id = :holidayId")
    suspend fun deleteHoliday(holidayId: String)

    // Notifications
    @Query("SELECT * FROM app_notifications ORDER BY triggerAtEpochMs DESC")
    fun observeNotifications(): Flow<List<AppNotificationEntity>>

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun upsertNotification(notification: AppNotificationEntity)

    @Query("UPDATE app_notifications SET read = 1 WHERE id = :id")
    suspend fun markNotificationRead(id: String)

    @Query("UPDATE app_notifications SET read = 1")
    suspend fun markAllNotificationsRead()

    @Query("DELETE FROM app_notifications")
    suspend fun clearNotifications()

    // AI Chat Messages
    @Query("SELECT * FROM ai_chat_messages ORDER BY timestampMs ASC")
    fun observeChatMessages(): Flow<List<AiChatMessageEntity>>

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertChatMessage(message: AiChatMessageEntity)

    @Query("DELETE FROM ai_chat_messages")
    suspend fun clearChatMessages()

    // Nuclear Clear (Delete All Local Data)
    @Query("DELETE FROM student_profile")
    suspend fun clearProfile()

    @Query("DELETE FROM subjects")
    suspend fun clearSubjects()

    @Query("DELETE FROM lessons")
    suspend fun clearLessons()

    @Query("DELETE FROM schedule_blocks")
    suspend fun clearScheduleBlocks()

    @Query("DELETE FROM exams")
    suspend fun clearExams()

    @Query("DELETE FROM focus_sessions")
    suspend fun clearFocusSessions()

    @Query("DELETE FROM study_notes")
    suspend fun clearNotes()

    @Query("DELETE FROM holidays")
    suspend fun clearHolidays()
}
